// Escolhe preto ou branco para texto sobre uma cor de fundo, pelo contraste
// WCAG (luminância relativa). Usado quando o tenant não define primaryInkColor.
const BLACK = '#000000'
const WHITE = '#ffffff'

function channelToLinear(channel: number): number {
  const c = channel / 255
  return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
}

export function relativeLuminance(hex: string): number {
  const value = hex.replace('#', '')
  const r = parseInt(value.slice(0, 2), 16)
  const g = parseInt(value.slice(2, 4), 16)
  const b = parseInt(value.slice(4, 6), 16)
  return 0.2126 * channelToLinear(r) + 0.7152 * channelToLinear(g) + 0.0722 * channelToLinear(b)
}

export function contrastInkColor(backgroundHex: string): string {
  const luminance = relativeLuminance(backgroundHex)
  const contrastWithBlack = (luminance + 0.05) / 0.05
  const contrastWithWhite = 1.05 / (luminance + 0.05)
  return contrastWithBlack >= contrastWithWhite ? BLACK : WHITE
}
